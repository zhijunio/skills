CREATE TABLE task_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id UUID NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    from_status VARCHAR(20),
    to_status VARCHAR(20) NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT task_status_history_from_check
        CHECK (from_status IS NULL OR from_status IN ('OPEN', 'IN_PROGRESS', 'DONE')),
    CONSTRAINT task_status_history_to_check
        CHECK (to_status IN ('OPEN', 'IN_PROGRESS', 'DONE'))
);

CREATE INDEX task_status_history_task_time_idx ON task_status_history (task_id, changed_at, id);
