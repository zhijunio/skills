#!/usr/bin/env python3
"""Generate a deterministic Markdown catalog from skill metadata and provenance."""
import argparse
from pathlib import Path
import re
import sys

from skills_ref.parser import parse_frontmatter
import strictyaml

ROOT = Path(__file__).resolve().parents[1]
COLLECTIONS = ("engineering", "spring-boot-skills", "collected-skills")
ROW = re.compile(r"^\| \[([^\]]+)\]\(\.\./([^)]*/SKILL\.md)\) \| ([^|]+) \|")
GROUP = re.compile(r"^\| ([A-Z]) \| (.+?) \|")


def cell(value):
    return " ".join(str(value).split()).replace("|", r"\|").replace("<", "&lt;").replace(">", "&gt;").replace("[", r"\[").replace("]", r"\]")


def render(root):
    provenance = (root / "docs/skill-provenance.md").read_text(encoding="utf-8")
    groups = {}
    sources = {}
    section = ""
    for line in provenance.splitlines():
        if line.startswith("## "):
            section = line
        if section == "## Source groups":
            match = GROUP.match(line)
            if match:
                key, label = match.groups()
                groups[key] = label
        if section == "## Per-skill register":
            match = ROW.match(line)
            if match:
                name, path, keys = match.groups()
                if path in sources:
                    raise ValueError(f"Duplicate provenance row: {path}")
                sources[path] = (name, keys.strip())
    rows = {key: [] for key in COLLECTIONS}
    seen = set()
    paths = set()
    for collection in COLLECTIONS:
        for marker in sorted((root / collection).rglob("SKILL.md")):
            path = marker.relative_to(root).as_posix()
            meta, _ = parse_frontmatter(marker.read_text(encoding="utf-8"))
            name, description = meta["name"], meta["description"]
            if name != marker.parent.name or name in seen:
                raise ValueError(f"Invalid or duplicate skill name: {path}")
            if path not in sources or sources[path][0] != name:
                raise ValueError(f"Missing or mismatched provenance: {path}")
            keys = sources[path][1]
            if any(key.strip() not in groups for key in keys.split("/")):
                raise ValueError(f"Unknown provenance key: {path}: {keys}")
            claude = meta.get("disable-model-invocation") in (True, "true")
            config = marker.parent / "agents/openai.yaml"
            codex = False
            if config.exists():
                policy = strictyaml.load(config.read_text(encoding="utf-8")).data.get("policy", {})
                codex = policy.get("allow_implicit_invocation") in (False, "false")
            if claude != codex:
                raise ValueError(f"Mismatched invocation restrictions: {path}")
            rows[collection].append((name, path, description, keys, "Explicit only" if claude else "Not restricted"))
            seen.add(name)
            paths.add(path)
    if not paths:
        raise ValueError("No skills found")
    if paths != set(sources):
        raise ValueError("Stale provenance entries: " + ", ".join(sorted(set(sources) - paths)))
    lines = [
        "# Skill Catalog", "",
        "<!-- Generated by scripts/generate-skill-catalog.py. Do not edit manually. -->", "",
        "Source: SKILL.md frontmatter, local invocation policies and the [provenance register](skill-provenance.md).",
        "Compatibility and limitations: [compatibility](skill-compatibility.md) and [distribution verification](verification/distribution.md).",
        "Invocation labels describe configuration, not proven runtime behavior. Source keys identify recorded provenance, not publication clearance.", "",
        "| Collection | Skills |", "| --- | ---: |",
    ]
    lines.extend(f"| {key} | {len(rows[key])} |" for key in COLLECTIONS)
    lines.extend([f"| Total | {len(paths)} |", "", "## Source keys", "", "| Key | Recorded source |", "| --- | --- |"])
    lines.extend(f"| {key} | {groups[key]} |" for key in sorted(groups))
    for collection in COLLECTIONS:
        lines.extend(["", f"## {collection}", "", "| Skill | Description | Source | Invocation policy |", "| --- | --- | --- | --- |"])
        for name, path, description, keys, policy in rows[collection]:
            lines.append(f"| [{name}](../{path}) | {cell(description)} | {keys} | {policy} |")
    lines.extend(["", "## Regenerate", "", "Run from the repository root:", "", "    python scripts/generate-skill-catalog.py", "    python scripts/generate-skill-catalog.py --check", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        output = render(ROOT)
        target = ROOT / "docs/skill-catalog.md"
        if args.check:
            if not target.exists() or target.read_bytes() != output.encode("utf-8"):
                raise ValueError("Catalog is missing or stale; run python scripts/generate-skill-catalog.py")
            print("Skill catalog is current.")
        else:
            target.write_bytes(output.encode("utf-8"))
            print("Generated docs/skill-catalog.md")
    except (ValueError, OSError, KeyError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
